package ru.eda.plgn.bizgen.core.generator_info

/**
 * Категория генератора.
 *
 * Определяет логическую группу генераторов тестовых данных.
 *
 * Используется для группировки в [GeneratorInfoProvider] и формирования категорийных MCP-инструментов (`ru-bizgen_generator_<category>`).
 *
 * @property title человекочитаемое имя категории для `title` MCP-тулов (например "Технические данные")
 * @author Dmitry_Emelyanenko
 */
enum class GeneratorCategory(val title: String) {

  /** Технические данные (UUID и т.п.). */
  TECHNICAL("Технические данные"),

  /** Банковские и платёжные реквизиты (счета, БИК, SWIFT, IBAN). */
  BANKING("Банковские и платёжные реквизиты"),

  /** Юридические реквизиты (ИНН, КПП, ОГРН, ОКТМО, наименования организаций). */
  LEGAL("Юридические реквизиты"),

  /** Адресно-территориальные данные (адрес, страна). */
  GEO("Адресно-территориальные данные"),

  /** Персональные данные (ФИО, паспорт, телефон, СНИЛС, карта). */
  PERSONAL("Персональные данные"),
}
